"""Recovery metrics, computed from ``.lab/timeline.json`` (stdlib only, so it is unit-tested).

Definitions (all measured, never estimated):
  RPO              attack_start - dump_started_at of the backup that was restored
  Orders lost      newest order id at attack start - newest order id in the restored database
  Detection delay  incident_detected - attack_start
  Response gap     restore_start - incident_detected (human or script reaction time)
  Restore time     restore_verified - restore_start
  RTO              restore_verified - incident_detected  (= response gap + restore time)
  Total downtime   restore_verified - attack_start
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime
from typing import Any

from lab.manifest import parse_iso

REQUIRED: dict[str, str] = {
    "attack_start": "lab attack",
    "incident_detected": "lab detect (run it before the attack)",
    "restore_start": "lab restore",
    "restore_verified": "lab restore",
    "restored_dump_started_at": "lab restore",
    "max_order_id_at_attack_start": "lab attack",
    "restored_max_order_id": "lab restore",
}


class MetricsError(ValueError):
    """The timeline is incomplete or out of order."""


@dataclass(frozen=True)
class Metrics:
    restored_backup_started: datetime
    attack_start: datetime
    incident_detected: datetime
    restore_start: datetime
    restore_verified: datetime
    rpo_s: float
    detection_delay_s: float
    response_gap_s: float
    restore_s: float
    rto_s: float
    downtime_s: float
    orders_lost: int


def _when(data: dict[str, Any], key: str) -> datetime:
    try:
        return parse_iso(data[key])
    except (TypeError, ValueError):
        raise MetricsError(f"timeline value {key!r} is not a valid time") from None


def compute_metrics(data: dict[str, Any]) -> Metrics:
    missing = [key for key in REQUIRED if data.get(key) is None]
    if missing:
        steps = sorted({REQUIRED[key] for key in missing})
        raise MetricsError(f"timeline is missing {', '.join(missing)}. Run: {'; '.join(steps)}")
    backup = _when(data, "restored_dump_started_at")
    attack = _when(data, "attack_start")
    detected = _when(data, "incident_detected")
    restore_start = _when(data, "restore_start")
    verified = _when(data, "restore_verified")
    if backup > attack:
        raise MetricsError("the restored backup started after the attack (it is not pre-attack)")
    if detected < attack:
        raise MetricsError("incident was detected before the attack: stale timeline, rerun")
    if restore_start < detected:
        raise MetricsError("restore started before the incident was detected: rerun in order")
    if verified < restore_start:
        raise MetricsError("restore finished before it started: stale timeline, rerun")
    lost = int(data["max_order_id_at_attack_start"]) - int(data["restored_max_order_id"])
    return Metrics(
        backup, attack, detected, restore_start, verified,
        rpo_s=(attack - backup).total_seconds(),
        detection_delay_s=(detected - attack).total_seconds(),
        response_gap_s=(restore_start - detected).total_seconds(),
        restore_s=(verified - restore_start).total_seconds(),
        rto_s=(verified - detected).total_seconds(),
        downtime_s=(verified - attack).total_seconds(),
        orders_lost=max(0, lost),
    )  # fmt: skip


def fmt_duration(seconds: float) -> str:
    if seconds < 60:
        return f"{seconds:.1f} s"
    minutes, rest = divmod(seconds, 60)
    return f"{int(minutes)} m {rest:.0f} s"


def _attempts_table(attempts: list[dict[str, str]]) -> str:
    lines = ["| Attempted action | Result | Error code |", "|---|---|---|"]
    lines += [f"| {a['action']} | {a['result']} | {a['code']} |" for a in attempts]
    return "\n".join(lines)


def render_results_md(m: Metrics, facts: dict[str, Any], generated: datetime) -> str:
    interval = facts.get("backup_interval_seconds")
    retention = facts.get("retention_minutes")
    attempts = facts.get("vault_attempts") or []
    rows = facts.get("encrypted_rows")
    parts = [
        "# Results of the last run",
        "",
        f"Generated by `lab report` at {generated:%Y-%m-%d %H:%M:%S}Z from `.lab/timeline.json`. "
        "One run, one laptop: numbers change every run.",
        "",
        "![Recovery timeline](docs/img/timeline.png)",
        "",
        "## Headline numbers",
        "",
        "| Metric | This run | How it is measured |",
        "|---|---|---|",
        f"| RPO (data at risk) | {fmt_duration(m.rpo_s)} | attack start minus start of the "
        "restored backup's snapshot |",
        f"| Orders lost | {m.orders_lost} | newest order id at attack start minus newest id "
        "in the restored database |",
        f"| Detection delay | {fmt_duration(m.detection_delay_s)} | health check flagged the "
        "damage after the attack began (polls every 5 s) |",
        f"| Response gap | {fmt_duration(m.response_gap_s)} | detection until the restore "
        "command started |",
        f"| Restore time | {fmt_duration(m.restore_s)} | restore start until verification passed |",
        f"| RTO | {fmt_duration(m.rto_s)} | detection until a verified restore (response gap "
        "+ restore time) |",
        f"| Total downtime | {fmt_duration(m.downtime_s)} | attack start until a verified "
        "restore |",
        "",
        "## Timeline (UTC)",
        "",
        "| Moment | Time |",
        "|---|---|",
        f"| Restored backup's snapshot taken | {m.restored_backup_started:%H:%M:%S.%f}Z |",
        f"| Attack starts | {m.attack_start:%H:%M:%S.%f}Z |",
        f"| Incident detected | {m.incident_detected:%H:%M:%S.%f}Z |",
        f"| Restore starts | {m.restore_start:%H:%M:%S.%f}Z |",
        f"| Restore verified | {m.restore_verified:%H:%M:%S.%f}Z |",
        "",
    ]
    if attempts:
        survived = ""
        if facts.get("locked_objects_targeted"):
            survived = (
                f" {facts['locked_objects_surviving']} of {facts['locked_objects_targeted']} "
                "locked backup objects were still retrievable afterwards."
            )
        parts += [
            "## What the attacker tried against the vault",
            "",
            _attempts_table(attempts),
            "",
            "A delete without a version id only adds a delete marker, and an overwrite only adds "
            "a new version: neither touches the locked original. Deleting the bucket failed "
            "because it was not empty, not because of the lock." + survived,
            "",
        ]
    limits = [
        "The dataset is tiny (about 205,000 rows, roughly 2 MB), so restore time says nothing "
        "about production-sized databases.",
        "RTO here starts when detection fires. The demo triggers the restore automatically; a "
        f"person would add their own reaction time (this run's response gap was "
        f"{fmt_duration(m.response_gap_s)}).",
        f"RPO is bounded by the backup interval ({interval} s in this run) and this is one "
        "sample: it can land anywhere from zero up to that interval."
        if interval
        else "RPO is bounded by the backup interval and this is one sample.",
        "Detection delay is bounded by the 5 s polling interval.",
        "The attacker is a simulation on a local lab database; it is not a test of any "
        "vendor's product."
        + (f" Retention was {retention} minutes so the lab stays tidy." if retention else ""),
    ]
    if rows:
        limits.insert(0, f"The simulated attack encrypted {rows:,} rows in one transaction.")
    parts += ["## Read this before quoting the numbers", ""] + [f"- {x}" for x in limits]
    return "\n".join(parts) + "\n"
